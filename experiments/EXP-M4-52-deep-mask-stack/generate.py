#!/usr/bin/env python3
"""Generate own-source, observably nested MSL kernels."""

from pathlib import Path


DEPTHS = tuple(range(1, 13)) + (16, 24, 32)
MAX_DEPTH = max(DEPTHS)
LANES = 16
STRIDE = 4 + 2 * MAX_DEPTH


def emit_level(lines, level, depth, indent):
    pad = " " * indent
    bit = 1 << level
    then_mul = 3 + 2 * level
    then_add = 0x10203041 + level * 0x01010101
    else_xor = 0x81020408 ^ (level * 0x00110101)
    post_mul = 5 + 2 * level
    post_add = 0x21314151 + level * 0x000f0103
    trace = 4 + 2 * level

    lines += [
        f"{pad}if ((path & 0x{bit:08x}u) != 0u) {{",
        f"{pad}    value = value * {then_mul}u + 0x{then_add & 0xffffffff:08x}u;",
        f"{pad}    out[base + {trace}u] = value ^ 0x{(0x40000000 | level):08x}u;",
        f"{pad}    visited |= 0x{bit:08x}u;",
    ]
    if level + 1 < depth:
        emit_level(lines, level + 1, depth, indent + 4)
    lines += [
        f"{pad}    value = value * {post_mul}u + 0x{post_add & 0xffffffff:08x}u;",
        f"{pad}    out[base + {trace + 1}u] = value ^ 0x{(0x50000000 | level):08x}u;",
        f"{pad}}} else {{",
        f"{pad}    value ^= 0x{else_xor & 0xffffffff:08x}u;",
        f"{pad}    out[base + {trace}u] = value ^ 0x{(0x60000000 | level):08x}u;",
        f"{pad}    value += 0x{(0x31415927 + level * 0x00010003) & 0xffffffff:08x}u;",
        f"{pad}    out[base + {trace + 1}u] = value ^ 0x{(0x70000000 | level):08x}u;",
        f"{pad}}}",
    ]


def kernel(depth):
    lines = [
        f"kernel void nested_{depth}(device uint *out [[buffer(0)]],",
        "                      device const uint *paths [[buffer(1)]],",
        "                      device const uint *salts [[buffer(2)]],",
        "                      uint lane [[thread_position_in_grid]])",
        "{",
        f"    const uint base = lane * {STRIDE}u;",
        "    const uint path = paths[lane];",
        f"    uint value = salts[lane] ^ 0x{(0x0badc000 | depth):08x}u;",
        "    uint visited = 0u;",
    ]
    emit_level(lines, 0, depth, 4)
    lines += [
        "    out[base + 0u] = value;",
        "    out[base + 1u] = visited;",
        "    out[base + 2u] = path;",
        f"    out[base + 3u] = 0xd0000000u | {depth}u;",
        "}",
    ]
    return "\n".join(lines)


def source():
    header = """// Generated by generate.py: clean-room deep mask-stack probes.
#include <metal_stdlib>
using namespace metal;
"""
    return header + "\n\n".join(kernel(depth) for depth in DEPTHS) + "\n"


def main():
    output = Path(__file__).with_name("deep_mask_stack.metal")
    output.write_text(source())
    print(output)


if __name__ == "__main__":
    main()
